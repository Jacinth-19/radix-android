#!/usr/bin/env python3
"""Student UI QA in Chromium. This is not Android device-runtime verification."""
from pathlib import Path
import json
from playwright.sync_api import sync_playwright, expect

root=Path(__file__).resolve().parent.parent
screens=root/'design'
checks=[]
def passed(name):
    checks.append(name)
    print('PASS:',name,flush=True)

with sync_playwright() as p:
    browser=p.chromium.launch(args=['--no-sandbox','--disable-dev-shm-usage'])
    ctx=browser.new_context(viewport={'width':1440,'height':1000},permissions=['clipboard-read','clipboard-write'])
    page=ctx.new_page();errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto('http://127.0.0.1:3000/',wait_until='networkidle')
    page.evaluate('document.fonts.ready')
    def close():
        page.locator('#base-dialog [data-action="close-dialog"]').click()
    def number(value,base=10):
        page.locator(f'.base-chip[data-base="{base}"]').click()
        page.locator('#number-input').fill(value)
    def worksheet(value,base=10,target=2):
        number(value,base)
        page.locator('#show-working').click()
        if target!=2:page.locator('#work-target').select_option(str(target))
    def vars(n):page.locator(f'[data-student="variables"][data-n="{n}"]').click()
    def form(value):page.locator(f'[data-student="form"][data-form="{value}"]').click()
    def lists(terms,dc=''):
        if page.locator('.k-inputs').get_attribute('open') is None:page.locator('.k-inputs summary').click()
        page.locator('#k-dc').fill('')
        page.locator('#k-terms').fill(terms)
        page.locator('#k-dc').fill(dc)
    def cells():return page.locator('#k-grid .k-cell strong').all_text_contents()
    def select(indices):
        for i in indices:page.locator(f'#k-grid [data-index="{i}"]').click()
    def checked():page.locator('[data-student="check-group"]').click()
    def clear():page.locator('[data-student="clear-selection"]').click()

    worksheet('13')
    expect(page.locator('.work-answer .mono')).to_have_text('1101')
    expect(page.locator('.work-lines').nth(1)).to_contain_text('13 ÷ 2 = 6, remainder 1 (1)')
    expect(page.locator('.work-section').nth(1)).to_contain_text('bottom to top')
    passed('Integer working exposes correct place values, divisions and reverse remainder order')
    page.locator('#work-target').select_option('36')
    expect(page.locator('.work-answer .mono')).to_have_text('D')
    expect(page.locator('#work-target option')).to_have_count(35)
    passed('Working target selector supports every base from 2 to 36')
    page.locator('[data-student="copy-working"]').click()
    text=page.evaluate('navigator.clipboard.readText()')
    assert '13 (base 10) → D (base 36)' in text and 'BOTTOM TO TOP' in text
    passed('Full conversion working copies as multi-line text')
    close();worksheet('0.625')
    expect(page.locator('.work-answer .mono')).to_have_text('0.101')
    expect(page.locator('.work-section').nth(2)).to_contain_text('top to bottom')
    expect(page.locator('.work-section').nth(2)).to_contain_text('Remainder zero')
    passed('Fractional working keeps top-to-bottom order and explains termination')
    close();worksheet('-10.625')
    expect(page.locator('.work-answer .mono')).to_have_text('-1010.101')
    expect(page.locator('.work-warning')).to_contain_text("not fixed-width two's complement")
    page.screenshot(path=str(screens/'student-working-desktop.png'))
    passed('Negative working restores sign rather than implying two’s complement')
    close();worksheet('0.1(6)')
    expect(page.locator('.work-answer .mono')).to_have_text('0.0(01)')
    expect(page.locator('.work-section').first).to_contain_text('1/15')
    expect(page.locator('.work-section').nth(2)).to_contain_text('fractional step 2')
    expect(page.locator('.work-answer small')).to_have_text('Exact')
    passed('Recurring source tails use a geometric series and repeated-remainder cycles are exact')
    close();worksheet('0.('+('0123456789'*4)+')',target=3)
    expect(page.locator('.work-answer small')).to_contain_text('Truncated at 24')
    expect(page.locator('.work-section').nth(2)).to_contain_text('truncated approximation')
    passed('Precision limit is explicitly approximate, never presented as exact')
    close();worksheet('10101.101',base=2,target=16)
    expect(page.locator('.work-answer .mono')).to_have_text('15.A')
    expect(page.locator('.work-section').last).to_contain_text('Integer 0001 → 1')
    expect(page.locator('.work-section').last).to_contain_text('Fraction 1010 → A')
    passed('Bit-grouping shortcut pads integer left and fraction right')
    close();worksheet('9'*64)
    expect(page.locator('.extra-steps')).to_have_count(2)
    page.locator('.extra-steps').last.locator('summary').click()
    expect(page.locator('.extra-steps').last).to_have_attribute('open','')
    assert page.locator('#base-dialog').evaluate('(el)=>el.scrollWidth<=el.clientWidth')
    passed('Long working stays locally scrollable with expandable steps')
    close();number('2',base=2)
    expect(page.locator('#show-working')).to_be_disabled()
    passed('Invalid source disables working and cannot open a plausible worksheet')

    page.locator('.topnav [data-tab="kmap"]').click()
    expect(page.locator('#k-expression')).to_have_text('A + B')
    expect(page.locator('#k-grid [data-index="3"] .k-outline')).to_have_count(2)
    expect(page.locator('#k-grid [data-index="3"] .k-members')).to_have_text('G1 G2')
    passed('Default K-map rewards immediately and clearly shows legal overlap')
    original=cells();form('POS')
    eq_expression='(A + B)'
    expect(page.locator('#k-expression')).to_have_text(eq_expression)
    assert cells()==original
    expect(page.locator('#k-terms')).to_have_value('0')
    passed('Switching SOP/POS preserves the truth table and recalculates the target list')
    vars(3);form('SOP')
    assert page.locator('#k-grid .k-cell').evaluate_all('(els)=>els.map(e=>Number(e.dataset.index))')==[0,1,3,2,4,5,7,6]
    lists('0,2')
    expect(page.locator('#k-expression')).to_have_text("A'C'")
    page.locator('[data-student="highlight"][data-group="0"]').click()
    expect(page.locator('.group-detail')).to_have_attribute('open','')
    expect(page.locator('.group-detail')).to_contain_text('wraps across an edge')
    expect(page.locator('.group-detail')).to_contain_text('changes')
    passed('Three-variable Gray order and horizontal wrap produce a correct explanation')
    page.locator('[data-student="truth"]').click()
    expect(page.locator('#k-truth tbody tr')).to_have_count(8)
    assert page.locator('#k-truth tbody tr').evaluate_all('(rows)=>rows.every(r=>r.cells[2].textContent===r.cells[3].textContent)')
    passed('Truth-table view independently exposes every specified output')
    page.locator('[data-student="manual"]').click();select([0,2]);checked()
    expect(page.locator('.group-feedback')).to_have_class('group-feedback valid')
    expect(page.locator('.group-feedback')).to_contain_text('Opposite edges')
    passed('Manual group checker accepts an opposite-edge pair')
    clear();select([0,1,2]);checked()
    expect(page.locator('.group-feedback')).to_contain_text('power-of-two')
    passed('Manual checker rejects a group of three with a beginner-friendly explanation')
    vars(2);lists('0,1,2,3')
    page.locator('[data-student="manual"]').click();select([0,3]);checked()
    expect(page.locator('.group-feedback')).to_contain_text('Diagonal-only')
    passed('Manual checker rejects diagonal-only pairs even when both outputs are one')
    clear();select([0]);checked()
    expect(page.locator('.group-feedback')).to_have_class('group-feedback valid')
    expect(page.locator('.group-feedback')).to_contain_text('grow')
    passed('A legal but non-maximal singleton receives useful growth feedback')
    clear();select([0,1,2,3]);checked()
    expect(page.locator('.group-feedback')).to_contain_text('maximal')
    passed('Manual checker accepts a maximal whole-map group')
    vars(2);lists('', '0,1')
    page.locator('[data-student="manual"]').click();select([0,1]);checked()
    expect(page.locator('.group-feedback')).to_contain_text('not only')
    passed('All-X groups are rejected because they cover no required output')
    lists('0','0,1')
    expect(page.locator('#k-input-error')).to_contain_text('also be a don’t-care'.replace('don’t',"don't"))
    expect(page.locator('#k-expression')).to_have_count(0)
    expect(page.locator('#k-grid .k-cell:disabled')).to_have_count(4)
    passed('Conflicting input lists pause solving, hide stale answers and disable map edits')
    lists('4')
    expect(page.locator('#k-input-error')).to_contain_text('0–3')
    lists('1, 1, 2,')
    expect(page.locator('#k-expression')).to_have_text("A'B + AB'")
    passed('Out-of-range lists reject clearly; duplicate and trailing indices recover cleanly')
    vars(4);lists('0,2,8,10')
    expect(page.locator('#k-expression')).to_have_text("B'D'")
    assert page.locator('.k-col-label').all_text_contents()==['00','01','11','10']
    assert page.locator('.k-row-label').all_text_contents()==['00','01','11','10']
    page.locator('[data-student="highlight"][data-group="0"]').click()
    expect(page.locator('.group-detail')).to_contain_text('wraps across an edge')
    page.screenshot(path=str(screens/'student-kmap-desktop.png'),full_page=True)
    passed('Four-variable corner wrap is one group on Gray-code rows and columns')
    form('POS');lists('0,2,8,10')
    expect(page.locator('#k-expression')).to_have_text('(B + D)')
    passed('Four-variable POS zero-corner grouping uses the reversed complement rule')
    form('SOP');lists('1,3,7,11,15','5,9,13')
    expect(page.locator('#k-expression')).to_have_text('D')
    expect(page.locator('#k-grid .dc')).to_have_count(3)
    page.locator('[data-student="truth"]').click()
    expect(page.locator('#k-truth')).to_contain_text('(optional)')
    passed('Optional Xs enlarge an octet and truth-table display distinguishes them')
    page.reload(wait_until='networkidle');page.locator('.topnav [data-tab="kmap"]').click()
    expect(page.locator('#k-expression')).to_have_text('D')
    expect(page.locator('#k-grid .k-cell')).to_have_count(16)
    expect(page.locator('#k-dc')).to_have_value('5, 9, 13')
    passed('K-map values, dimensions, form and don’t-cares persist locally across reload')

    vars(6);expect(page.locator('#k-grid .k-cell')).to_have_count(64);expect(page.locator('.kmap-panel')).to_contain_text('rotate your device to landscape')
    page.locator('.k-inputs summary').click();page.locator('#k-notation').fill('F(A,B,C,D,E,F)=Σm(63)');page.locator('[data-student="notation"]').click()
    notation_rows=page.locator('#k-grid .k-cell').evaluate_all('(els)=>els.map(e=>[Number(e.dataset.index),e.querySelector("strong").textContent])')
    assert len(notation_rows)==64 and sum(value=='1' for _,value in notation_rows)==1 and dict(notation_rows)[63]=='1'
    page.locator('.k-inputs summary').click();page.locator('#k-notation').fill('F(A,B,C,D,F,E)=Σm(63)');page.locator('[data-student="notation"]').click()
    expect(page.locator('#k-notation-error')).to_contain_text('A, B, C');assert dict(page.locator('#k-grid .k-cell').evaluate_all('(els)=>els.map(e=>[Number(e.dataset.index),e.querySelector("strong").textContent])'))==dict(notation_rows)
    passed('Six-variable 8×8 K-map loads Σm(63), gives landscape guidance and rejects shuffled A–F axes without mutation')

    for i in range(24):
        page.locator('[data-student="examples"]').click()
        expect(page.locator('.example-list button')).to_have_count(24)
        page.locator('.example-list button').nth(i).click()
        expect(page.locator('#k-expression')).to_have_count(0)
        expect(page.locator('.exercise-hint')).to_be_visible()
        page.locator('[data-student="reveal"]').click()
        expect(page.locator('#k-expression')).to_be_visible()
        expect(page.locator('.exercise-lesson')).to_be_visible()
        expected=page.evaluate(f"(()=>{{const e=RadixKMap.exercises[{i}];return RadixKMap.solve(e.variables,e.cells(),e.form).expression}})()")
        expect(page.locator('#k-expression')).to_have_text(expected)
    passed('All 24 challenges load, hide the answer, reveal the correct result and show the lesson')
    page.locator('[data-student="copy-kmap"]').click()
    text=page.evaluate('navigator.clipboard.readText()')
    assert 'Truth table:' in text and 'Gray order:' in text
    passed('K-map copy includes expression, grouping working and truth table')

    # Independent phone state; small widths, short viewport, both palettes.
    phone_ctx=browser.new_context(viewport={'width':390,'height':844},device_scale_factor=2,is_mobile=True,has_touch=True)
    phone=phone_ctx.new_page();phone.on('pageerror',lambda e:errors.append(str(e)))
    phone.goto('http://127.0.0.1:3000/',wait_until='networkidle')
    phone.locator('.mobile-nav [data-tab="kmap"]').click()
    phone.locator('[data-student="examples"]').click();phone.locator('.example-list button').nth(14).click()
    phone.locator('[data-student="reveal"]').click();phone.locator('[data-student="highlight"][data-group="0"]').click()
    phone.screenshot(path=str(screens/'student-kmap-phone-dark.png'),full_page=True)
    phone.locator('#theme-toggle').click()
    phone.screenshot(path=str(screens/'student-kmap-phone-light.png'),full_page=True)
    for width,height in [(390,844),(320,640),(390,520),(768,900)]:
        phone.set_viewport_size({'width':width,'height':height})
        assert phone.evaluate('document.documentElement.scrollWidth<=innerWidth'),(width,height)
    passed('K-map UI has no page overflow on phone, keyboard-height and tablet viewports')
    phone.set_viewport_size({'width':320,'height':640})
    phone.locator('.mobile-nav [data-tab="convert"]').click();phone.locator('#number-input').fill('0.625')
    phone.locator('#show-working').click()
    expect(phone.locator('.work-answer .mono')).to_have_text('0.101')
    assert phone.locator('#base-dialog').evaluate('(el)=>el.scrollWidth<=el.clientWidth')
    phone.screenshot(path=str(screens/'student-working-phone.png'))
    passed('Working sheet is readable and contained at 320px width')
    # Clipboard denial must preserve the entire report, not flatten it into an input.
    phone.evaluate("navigator.clipboard.writeText=async()=>{throw Error('Blocked in test')};document.execCommand=()=>false")
    phone.locator('[data-student="copy-working"]').click()
    expect(phone.locator('textarea#manual-copy')).to_be_visible()
    assert 'TOP TO BOTTOM' in phone.locator('#manual-copy').input_value()
    assert '\n' in phone.locator('#manual-copy').input_value()
    passed('Clipboard denial keeps a selectable multi-line report inside the open dialog')

    embedded=ctx.new_page();embedded.on('pageerror',lambda e:errors.append(str(e)))
    embedded.set_content('<iframe id="app" sandbox="allow-scripts" style="width:100%;height:900px;border:0"></iframe>')
    embedded.eval_on_selector('#app','(el,html)=>el.srcdoc=html',(root/'web/index.html').read_text())
    frame=embedded.frame_locator('#app')
    frame.locator('#show-working').click()
    expect(frame.locator('.work-answer .mono')).to_have_text('11111111')
    frame.locator('[data-action="close-dialog"]').click()
    frame.locator('.topnav [data-tab="kmap"]').click()
    expect(frame.locator('#k-expression')).to_have_text('A + B')
    passed('Student engines and screens work in the offline opaque-origin file viewer')
    assert not errors,errors
    passed('No student-screen JavaScript runtime errors')
    browser.close()
report={'status':'pass','checks':len(checks),'tests':checks,'scope':'Chromium browser companion, not Android device runtime','exercisesInteractivelyChecked':24}
(root/'design/student-ui-results.json').write_text(json.dumps(report,indent=2)+'\n')
print(f'PASS: {len(checks)} student browser UX checks.',flush=True)
