    fun translate(source:String,language:String):String {
        val normalizedLanguage=language.lowercase()
        if(normalizedLanguage !in setOf("fr","es","pt"))return source
        if(source!=source.trim()) {
            val leading=source.takeWhile{it.isWhitespace()}
            val trailing=source.takeLastWhile{it.isWhitespace()}
            val core=source.trim()
            val translated=translate(core,normalizedLanguage)
            if(translated!=core)return leading+translated+trailing
        }
        if(source.startsWith("• ")) {
            val body=source.substring(2)
            val translated=translate(body,normalizedLanguage)
            if(translated!=body)return "• $translated"
        }
        val translations=when(normalizedLanguage) {"fr"->fr;"es"->es;else->pt}
        translations[source]?.let{return it}
        CoreEngineTranslations.translate(source,language)?.let{return it}
        WorkingTranslations.translate(source,language)?.let{return it}
        GameTranslations.translate(source,language)?.let{return it}
        UiTranslationsExtra.translate(source,language)?.let{return it}
        BackupTranslations.translate(source,language)?.let{return it}
        UiTranslationsTechnical.translate(source,language)?.let{return it}
        UiTranslationsStudy.translate(source,language)?.let{return it}
        LearningPathTranslations.translate(source,language)?.let{return it}
        KMapContentTranslations.translate(source,language)?.let{return it}
        LogicCatalogTranslations.translate(source,language)?.let{return it}
        PracticeTextTranslations.translate(source,language)?.let{return it}
        PracticeTextTranslations2.translate(source,language)?.let{return it}
        PracticeTextTranslations3.translate(source,language)?.let{return it}
        PracticeChoiceTranslations.translate(source,language)?.let{return it}
        val baseLabel=Regex("^Number to convert in base (.+)$").matchEntire(source)?.groupValues?.get(1)
        if(baseLabel!=null)return when(language.lowercase()) {"fr"->"Nombre à convertir en base $baseLabel";"es"->"Número para convertir en base $baseLabel";else->"Número para converter na base $baseLabel"}
        val quickBase=Regex("^Copy (.+) quick result$").matchEntire(source)?.groupValues?.get(1)
        if(quickBase!=null)return when(language.lowercase()) {"fr"->"Copier le résultat rapide $quickBase";"es"->"Copiar el resultado rápido $quickBase";else->"Copiar o resultado rápido $quickBase"}
        val bit=Regex("^Toggle bit (\\d+), weight (\\d+)$").matchEntire(source)
        if(bit!=null)return when(language.lowercase()) {"fr"->"Basculer le bit ${bit.groupValues[1]}, poids ${bit.groupValues[2]}";"es"->"Cambiar el bit ${bit.groupValues[1]}, peso ${bit.groupValues[2]}";else->"Alternar o bit ${bit.groupValues[1]}, peso ${bit.groupValues[2]}"}
        val groupSize=Regex("^Select an adjacent power-of-two group \\(1–(\\d+) cells\\), then check it\\.$").matchEntire(source)?.groupValues?.get(1)
        if(groupSize!=null)return when(language.lowercase()) {"fr"->"Sélectionnez un groupe adjacent de taille puissance de deux (1–$groupSize cases), puis vérifiez-le.";"es"->"Selecciona un grupo adyacente de tamaño potencia de dos (1–$groupSize celdas) y compruébalo.";else->"Selecione um grupo adjacente com tamanho potência de dois (1–$groupSize células) e confira."}
        val selectedCount=Regex("^(\\d+) selected$").matchEntire(source)?.groupValues?.get(1)
        if(selectedCount!=null)return when(language.lowercase()) {"fr"->"$selectedCount sélectionnés";"es"->"$selectedCount seleccionados";else->"$selectedCount selecionados"}
        val variables=Regex("^(\\d+) vars$").matchEntire(source)?.groupValues?.get(1)
        if(variables!=null)return when(language.lowercase()) {"fr"->"$variables variables";"es"->"$variables variables";else->"$variables variáveis"}
        val rows=Regex("^(\\d+) ROWS · ALL INPUT COMBINATIONS$").matchEntire(source)?.groupValues?.get(1)
        if(rows!=null)return when(language.lowercase()) {"fr"->"$rows LIGNES · TOUTES LES COMBINAISONS D’ENTRÉES";"es"->"$rows FILAS · TODAS LAS COMBINACIONES DE ENTRADA";else->"$rows LINHAS · TODAS AS COMBINAÇÕES DE ENTRADA"}
        return source
    }
